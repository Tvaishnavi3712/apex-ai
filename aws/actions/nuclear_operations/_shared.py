# ---------------------------------------------------------------------------
# Date helpers
# ---------------------------------------------------------------------------

def parse_date(value: Any) -> Optional[datetime]:
    """Best-effort ISO-8601 / common-date parser. Returns None on failure."""
    if value is None:
        return None
    if isinstance(value, datetime):
        return value
    s = str(value).strip()
    if not s:
        return None
    # Try a few common formats
    for fmt in ("%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M:%SZ", "%Y-%m-%d %H:%M:%S",
                "%Y-%m-%d", "%m/%d/%Y", "%m-%d-%Y"):
        try:
            return datetime.strptime(s[: len(fmt) + 5], fmt)
        except (ValueError, TypeError):
            continue
    try:
        return datetime.fromisoformat(s.replace("Z", "+00:00"))
    except (ValueError, TypeError):
        return None


def days_between(a: Any, b: Any) -> Optional[int]:
    """Whole-day delta between two parseable dates. None if either fails."""
    da, db = parse_date(a), parse_date(b)
    if da is None or db is None:
        return None
    return (db - da).days


def within_window(when: Any, *, days: int, reference: Optional[datetime] = None) -> bool:
    """Return True if `when` is within `days` days before `reference` (default: now)."""
    ref = reference or datetime.utcnow()
    parsed = parse_date(when)
    if parsed is None:
        return False
    return ref - timedelta(days=days) <= parsed <= ref


# ---------------------------------------------------------------------------
# Lookup helpers
# ---------------------------------------------------------------------------

def filter_by_field(rows: List[Dict[str, Any]], field: str, value: Any) -> List[Dict[str, Any]]:
    """Return subset of `rows` where row[field] == value."""
    return [r for r in rows if r.get(field) == value]


def index_by(rows: List[Dict[str, Any]], field: str) -> Dict[Any, Dict[str, Any]]:
    """Build a {field_value: row} index. Last write wins on duplicates."""
    return {r.get(field): r for r in rows if r.get(field) is not None}
