"""
Shared utilities for nuclear_operations action handlers.

All handlers in this package read from the synthetic-data corpus generated by
`synthetic-data/nuclear_operations/generate.py`. The synthetic data may not
exist yet during early development — these helpers degrade gracefully and
return a uniform error envelope so handlers can short-circuit cleanly.

Cached loaders (LRU) keep warm-container invocations under a few hundred
microseconds after the first read.
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timedelta
from functools import lru_cache
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple


# ---------------------------------------------------------------------------
# Path resolution
# ---------------------------------------------------------------------------

# actions/nuclear_operations/_shared.py -> parents[2] is aws/
_AWS_ROOT = Path(__file__).resolve().parents[2]
_DATA_ROOT = _AWS_ROOT / "synthetic-data" / "nuclear_operations"


def data_path(*parts: str) -> Path:
    """Build an absolute path under synthetic-data/nuclear_operations/."""
    # Allow override via env var for tests / alternate corpora.
    override = os.environ.get("APEX_NUCLEAR_DATA_DIR")
    base = Path(override).resolve() if override else _DATA_ROOT
    return base.joinpath(*parts)


# ---------------------------------------------------------------------------
# Error envelope
# ---------------------------------------------------------------------------

def missing_data_envelope(missing: str) -> Dict[str, Any]:
    """Uniform envelope returned when a required synthetic-data file is missing.

    Args:
        missing: Path or filename that was expected but not found.

    Returns:
        Standard error dict with status, error_type, message, missing_path.
    """
    return {
        "status": "error",
        "error_type": "synthetic_data_not_generated",
        "message": "Run synthetic-data/nuclear_operations/generate.py first",
        "missing_path": str(missing),
    }


def not_found_envelope(resource: str, identifier: str) -> Dict[str, Any]:
    """Envelope returned when a referenced record/file legitimately does not exist."""
    return {
        "status": "not_found",
        "resource": resource,
        "identifier": identifier,
        "message": f"{resource} '{identifier}' was not found in the corpus",
    }


# ---------------------------------------------------------------------------
# Cached JSON loaders
# ---------------------------------------------------------------------------

def _read_json(path: Path) -> Optional[Any]:
    """Read a JSON file. Returns None if missing or unparseable."""
    try:
        if not path.exists():
            return None
        with path.open("r", encoding="utf-8") as fp:
            return json.load(fp)
    except (OSError, json.JSONDecodeError):
        return None


@lru_cache(maxsize=1)
def _cache_key() -> str:
    """Cache invalidator. Tests can clear the LRU caches by calling clear_caches()."""
    return os.environ.get("APEX_NUCLEAR_DATA_DIR", "default")


def clear_caches() -> None:
    """Clear all module-scoped caches. Used by tests via monkeypatch."""
    load_work_orders.cache_clear()
    load_personnel.cache_clear()
    load_change_history.cache_clear()
    load_failure_events.cache_clear()
    load_failure_mode_catalog.cache_clear()
    load_equipment.cache_clear()
    load_pm_schedule.cache_clear()
    load_seed_anomalies.cache_clear()
    _cache_key.cache_clear()


@lru_cache(maxsize=1)
def load_work_orders() -> Optional[List[Dict[str, Any]]]:
    """Load work_orders.json. Returns None if missing."""
    _ = _cache_key()  # tie cache to env override
    return _read_json(data_path("work_orders.json"))


